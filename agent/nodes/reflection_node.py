"""Reflection node for lightweight output quality checks."""

from __future__ import annotations

from agent.state import ResearchState


def reflection_node(state: ResearchState) -> dict:
    """Review the generated report for source grounding and uncertainty handling."""

    report = state.get("report", "")
    issues = _find_report_issues(state, report)
    reflection = {
        "passed": not issues,
        "issues": issues,
        "checks": [
            "source_links",
            "retrieved_memory",
            "external_results",
            "uncertainty_language",
            "daily_brief_output",
        ],
    }
    return {"reflection": reflection}


def _find_report_issues(state: ResearchState, report: str) -> list[str]:
    issues: list[str] = []
    task_type = state.get("task_type", "")
    research_results = state.get("research_results", [])
    retrieved_documents = state.get("retrieved_documents", [])

    if state.get("report_error"):
        issues.append("LLM provider failed; local fallback answer was used.")

    if task_type == "daily_brief":
        if not _has_daily_brief_output(research_results):
            issues.append("Daily brief task did not return an output_path.")
        return issues

    if research_results and "http" not in report and "Source:" not in report:
        issues.append("External results were available, but source links are missing.")
    if retrieved_documents and not _has_local_source_context(report):
        issues.append("Retrieved local/PDF evidence was available, but local source context is missing.")
    if not _has_uncertainty_language(report):
        issues.append("Uncertainty or evidence limitations are not explicit enough.")
    if "MockLLM" in report:
        issues.append("Answer was generated by MockLLM fallback.")

    return issues


def _has_local_source_context(report: str) -> bool:
    markers = ["file:", "heading_path:", "page:", "Sources Used", "Source:"]
    return any(marker in report for marker in markers)


def _has_daily_brief_output(results: list[dict]) -> bool:
    return any(result.get("type") == "daily_brief" and result.get("output_path") for result in results)


def _has_uncertainty_language(report: str) -> bool:
    markers = [
        "信息不足",
        "需要进一步",
        "未验证",
        "谨慎",
        "不足以判断",
        "不确定",
        "风险",
        "hypothesis",
        "unverified",
        "uncertain",
        "further",
    ]
    normalized = report.lower()
    return any(marker.lower() in normalized for marker in markers)
